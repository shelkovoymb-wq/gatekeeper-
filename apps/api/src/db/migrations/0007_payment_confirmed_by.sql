-- Кто перевёл платёж в succeeded.
--
-- NULL — провайдер: подписанный вебхук ЮKassa/Prodamus/CloudPayments/Robokassa
-- или подтверждение встречным запросом в API магазина. Такому платежу верим
-- полностью: за ним стоит подпись или ответ платёжной системы.
--
-- 'client' — сам клиент отметил в кабинете «деньги получены». Так закрываются
-- прямые переводы (СБП, карта, счёт): у обычного банка вебхука нет, и без
-- этой отметки деньги приходили бы клиенту, а платформа их не видела — платёж
-- навсегда оставался бы pending и не попадал ни в оборот, ни в комиссию.
--
-- Колонка нужна именно отдельной, а не флагом в metadata: по ней считается
-- разбивка оборота в счёте (сколько подтверждено провайдером, сколько со слов
-- клиента), а это агрегат по всем платежам за период.

ALTER TABLE payments
  ADD COLUMN IF NOT EXISTS confirmed_by text,
  ADD COLUMN IF NOT EXISTS confirmed_at timestamptz;

-- Счёт за период агрегирует платежи клиента по (client_id, status, created_at);
-- confirmed_by читается там же, поэтому индекс покрывающий.
CREATE INDEX IF NOT EXISTS payments_client_period_idx
  ON payments (client_id, status, created_at);
